create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  display_name text not null,
  role text not null default 'inspector' check (role in ('admin', 'inspector')),
  created_at timestamptz not null default now()
);

-- Editable scoring thresholds. These are intentionally data, not hard-coded app logic.
-- Automatically create an application profile when a Supabase Auth user is created.
-- The first Auth user becomes the initial administrator; later users default to inspector.
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  initial_role text;
  initial_name text;
begin
  if exists (select 1 from public.profiles) then
    initial_role := 'inspector';
  else
    initial_role := 'admin';
  end if;

  initial_name := coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), split_part(coalesce(new.email, 'CAP User'), '@', 1));

  insert into public.profiles (id, email, display_name, role)
  values (new.id, coalesce(new.email, new.id::text), initial_name, initial_role)
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_auth_user();

-- If Auth users already existed before this migration, backfill their profiles.
-- The oldest existing Auth user becomes the initial administrator when no profile exists yet.
do $$
begin
  if not exists (select 1 from public.profiles) then
    insert into public.profiles (id, email, display_name, role)
    select u.id,
           coalesce(u.email, u.id::text),
           coalesce(nullif(u.raw_user_meta_data ->> 'display_name', ''), split_part(coalesce(u.email, 'CAP User'), '@', 1)),
           'admin'
    from auth.users u
    order by u.created_at asc
    limit 1
    on conflict (id) do nothing;
  end if;

  insert into public.profiles (id, email, display_name, role)
  select u.id,
         coalesce(u.email, u.id::text),
         coalesce(nullif(u.raw_user_meta_data ->> 'display_name', ''), split_part(coalesce(u.email, 'CAP User'), '@', 1)),
         'inspector'
  from auth.users u
  where not exists (select 1 from public.profiles p where p.id = u.id)
  on conflict (id) do nothing;
end;
$$;

create table if not exists public.grading_rules (
  grade_group text primary key check (grade_group in ('airman', 'nco_officer')),
  passing_min smallint not null check (passing_min between 0 and 10),
  excellent_min smallint not null check (excellent_min between 0 and 10),
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id),
  constraint grading_rules_order check (passing_min <= excellent_min)
);

insert into public.grading_rules (grade_group, passing_min, excellent_min)
values
  ('airman', 4, 6),
  ('nco_officer', 5, 8)
on conflict (grade_group) do nothing;

create table if not exists public.cadets (
