create table if not exists public.inspections (
  id bigint generated by default as identity primary key,
  client_uuid uuid unique,
  cadet_id bigint not null references public.cadets(id) on delete cascade,
  inspection_date date not null default current_date,
  grade_at_inspection text not null,
  grade_group text not null check (grade_group in ('airman', 'nco_officer')),
  personal_appearance smallint not null check (personal_appearance between 0 and 2),
  garments smallint not null check (garments between 0 and 2),
  accoutrements smallint not null check (accoutrements between 0 and 2),
  footwear smallint not null check (footwear between 0 and 2),
  military_bearing smallint not null check (military_bearing between 0 and 2),
  total_score smallint not null default 0 check (total_score between 0 and 10),
  overall_rating text not null default 'Needs Improvement' check (overall_rating in ('Needs Improvement', 'Satisfactory', 'Excellent')),
  passed boolean not null default false,
  notes text,
  evaluator_id uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);

create index if not exists inspections_cadet_date_idx on public.inspections(cadet_id, inspection_date desc);
